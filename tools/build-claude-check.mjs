#!/usr/bin/env node
/**
 * tools/build-claude-check.mjs — generates data/ClaudeCheckData.js (V184). DEV TOOL, run once per iteration.
 *
 *   node tools/build-claude-check.mjs --version V184 --categories "V174,V175,V176,V177,V178,V179,V180,V181,V182,V183,V184" [--date 2026-10-10]
 *        [--checklist docs/dev/Roles/Developer/TestingChecklist.json] [--ask docs/dev/Roles/Developer/ClaudeCheckAsk.json]
 *        [--out data/ClaudeCheckData.js] [--include-tested] [--strict]
 *
 * Reads TestingChecklist.json (the one source of truth for what to test) and the hand-written ClaudeCheckAsk.json
 * ({summary, date?, asks:[...], knownIssues:[...]}) and writes the bundled iteration data (schema omni-claude-check/1).
 * - categories: comma-separated, case-insensitive SUBSTRING match against the category name. A pattern that matches nothing is reported as MISSING.
 * - items already marked passed (tested === true) are skipped unless --include-tested.
 * - ids are stable: slug(category) . slug(feature), both capped; a duplicate gets "-2", "-3" and is reported (--strict turns that into an error).
 * - priority: 'high' for categories mentioning V183 / V182 and for any item whose text says "regress" or "persist"; else 'normal'.
 * - device: 'phone' (phone / 390 / mobile), else 'touch' (touch / long-press), else 'gpu' (GPU / fps / frame rate), else 'any'.
 * The output is validated with utils/DevClaudeCheckData.js before it is written (a bad file is never written).
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

export const slug = (s, max) => String(s ?? '').normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, max).replace(/-+$/g, '')
export const makeId = (category, feature) => `${slug(category, 30) || 'x'}.${slug(feature, 50) || 'x'}`

export function derivePriority (category, item) {
  const text = `${item.feature} ${item.howToReach} ${item.whatToCheck}`
  if (/V18[23]\b/.test(category) || /regress|persist/i.test(text)) return 'high'
  return 'normal'
}
export function deriveDevice (item) {
  const text = `${item.howToReach} ${item.whatToCheck}`
  if (/\bphones?\b|\b390\b|mobile/i.test(text)) return 'phone'
  if (/touch|long-press|long press/i.test(text)) return 'touch'
  if (/\bGPU\b|\bfps\b|frame ?rate/i.test(text)) return 'gpu'
  return 'any'
}

/** Pure: build the data object. Returns { data, missing, duplicates, matched }. */
export function buildData ({ checklist, ask, version, date, categories, includeTested = false }) {
  const pats = categories.map(c => c.trim().toLowerCase()).filter(Boolean)
  const cats = Array.isArray(checklist?.categories) ? checklist.categories : []
  const used = new Set(); const matched = []; const checks = []; const duplicates = []
  const ids = new Map()
  for (const cat of cats) {
    const name = String(cat.category ?? '')
    const hit = pats.filter(p => name.toLowerCase().includes(p))
    if (!hit.length) continue
    hit.forEach(p => used.add(p)); matched.push(name)
    for (const it of cat.items ?? []) {
      if (!includeTested && it.tested === true) continue
      const item = { feature: String(it.feature ?? ''), howToReach: String(it.howToReach ?? ''), whatToCheck: String(it.whatToCheck ?? '') }
      let id = makeId(name, item.feature)
      if (ids.has(id)) { const n = ids.get(id) + 1; ids.set(id, n); const nid = `${id}-${n}`; duplicates.push({ id, renamed: nid, feature: item.feature }); id = nid; ids.set(id, 1) } else ids.set(id, 1)
      checks.push({ id, category: name, feature: item.feature, howToReach: item.howToReach, whatToCheck: item.whatToCheck, priority: derivePriority(name, item), device: deriveDevice(item) })
    }
  }
  const data = {
    schema: 'omni-claude-check/1', version, date: date || ask?.date || new Date().toISOString().slice(0, 10), summary: String(ask?.summary ?? ''),
    checks, asks: Array.isArray(ask?.asks) ? ask.asks : [], knownIssues: Array.isArray(ask?.knownIssues) ? ask.knownIssues : [],
  }
  return { data, missing: pats.filter(p => !used.has(p)), duplicates, matched }
}

export const render = (data) => `/**\n * data/ClaudeCheckData.js — GENERATED by tools/build-claude-check.mjs. DO NOT EDIT BY HAND.\n * Edit docs/dev/Roles/Developer/TestingChecklist.json and ClaudeCheckAsk.json, then re-run the tool.\n * Read (validated) by utils/DevClaudeCheckData.js — DEV ONLY.\n */\nexport default ${JSON.stringify(data, null, 1)}\n`

function args (argv) {
  const o = {}
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    if (!a.startsWith('--')) continue
    const k = a.slice(2)
    if (['include-tested', 'strict'].includes(k)) o[k] = true
    else o[k] = argv[++i]
  }
  return o
}

async function main () {
  const o = args(process.argv.slice(2))
  const version = o.version
  if (!version || !o.categories) { console.error('usage: node tools/build-claude-check.mjs --version V184 --categories "V183,V184" [--date YYYY-MM-DD] [--checklist f] [--ask f] [--out f] [--include-tested] [--strict]'); process.exit(2) }
  const rel = (p, d) => path.resolve(ROOT, p || d)
  const checklist = JSON.parse(fs.readFileSync(rel(o.checklist, 'docs/dev/Roles/Developer/TestingChecklist.json'), 'utf8'))
  const ask = JSON.parse(fs.readFileSync(rel(o.ask, 'docs/dev/Roles/Developer/ClaudeCheckAsk.json'), 'utf8'))
  const r = buildData({ checklist, ask, version, date: o.date, categories: o.categories.split(','), includeTested: !!o['include-tested'] })
  const { validateData } = await import(pathToFileURL(path.join(ROOT, 'utils/DevClaudeCheckData.js')).href)
  const v = validateData(r.data)
  if (!v.ok || v.errors.length) { console.error('VALIDATION PROBLEMS:\n  ' + (v.errors.join('\n  ') || 'unusable data')); if (!v.ok) process.exit(1) }
  if (v.data.checks.length !== r.data.checks.length || v.data.asks.length !== r.data.asks.length) { console.error('Validation dropped items; fix the source documents. Nothing written.'); process.exit(1) }
  if (r.duplicates.length) { console.error('DUPLICATE ids (renamed with a suffix, keep the checklist order stable):\n  ' + r.duplicates.map(d => `${d.id} -> ${d.renamed} (${d.feature})`).join('\n  ')); if (o.strict) process.exit(1) }
  if (r.missing.length) console.error('MISSING categories (no category name contains): ' + r.missing.join(', '))
  const out = rel(o.out, 'data/ClaudeCheckData.js')
  fs.writeFileSync(out, render(r.data))
  console.log(`wrote ${path.relative(ROOT, out)}: ${r.data.checks.length} checks in ${r.matched.length} categories, ${r.data.asks.length} asks, ${r.data.knownIssues.length} known issues`)
  console.log('categories: ' + r.matched.join(' | '))
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) main().catch(e => { console.error(e); process.exit(1) })
