#!/usr/bin/env node
/**
 * tools/build-emoji-data.mjs — regenerates data/OmniEmojiData.js (V181)
 *
 * Usage:   npm install emojibase-data@17.0.0 --prefix /some/scratch/dir
 *          node tools/build-emoji-data.mjs /some/scratch/dir/node_modules/emojibase-data  data/OmniEmojiData.js
 *
 * Source: emojibase-data (MIT, https://github.com/milesj/emojibase), English "data.json" + "messages.json". Pinned: 17.0.0 (Unicode Emoji 17.0).
 * Kept: every FULLY-QUALIFIED base emoji (one entry per emoji; skin-tone variants are NOT listed, they hang off a base entry as `skins`
 *       and are dropped), groups 0 and 1 and 3..9. Dropped: the "components" group (skin tones, hair), regional-indicator letters and the
 *       other entries with no group.
 * Output: a plain ES module. One string per Unicode group, one line per emoji:  HEX-CODEPOINTS \t name \t keyword,keyword
 *         (hex keeps the file ASCII: tag-sequence flags such as England contain invisible characters that editors may strip).
 *         The runtime (data/OmniEmojiData.js) decodes lazily into [{e, n, g, k}].
 * The script checks that decoding the hex gives exactly the source `emoji` string, and fails otherwise.
 */
import fs from 'node:fs'
import path from 'node:path'

const [srcDir, outFile] = process.argv.slice(2)
if (!srcDir || !outFile) { console.error('usage: build-emoji-data.mjs <emojibase-data dir> <out file>'); process.exit(2) }
const read = (f) => JSON.parse(fs.readFileSync(path.join(srcDir, 'en', f), 'utf8'))
const pkg = JSON.parse(fs.readFileSync(path.join(srcDir, 'package.json'), 'utf8'))
const data = read('data.json')
const messages = read('messages.json')

// Unicode group order for the picker: emojibase group ids -> our order (component group 2 is dropped)
const GROUP_IDS = [0, 1, 3, 4, 5, 6, 7, 8, 9]
const GROUP_NAMES = ['Smileys & Emotion', 'People & Body', 'Animals & Nature', 'Food & Drink', 'Travel & Places', 'Activities', 'Objects', 'Symbols', 'Flags']
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1)
const clean = (s) => String(s).replace(/[\t\r\n|]+/g, ' ').trim()

const groups = GROUP_IDS.map(() => [])
let maxUnits = 0, maxName = 0, maxVersion = 0
const seen = new Set()
for (const e of data) {
  const gi = GROUP_IDS.indexOf(e.group)
  if (gi < 0) continue
  if (seen.has(e.emoji)) throw new Error('duplicate ' + e.hexcode)
  seen.add(e.emoji)
  // emojibase's `hexcode` can omit U+FE0F (minimally qualified); the `emoji` string is the fully-qualified form, so encode THAT
  const hexcode = [...e.emoji].map(c => c.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')).join('-')
  if (String.fromCodePoint(...hexcode.split('-').map(h => parseInt(h, 16))) !== e.emoji) throw new Error('round trip failed ' + e.hexcode)
  const name = cap(clean(e.label))
  const tags = (e.tags ?? []).map(clean).filter(Boolean).filter(t => t.toLowerCase() !== name.toLowerCase())
  groups[gi].push(`${hexcode}\t${name}\t${tags.join(',')}`)
  maxUnits = Math.max(maxUnits, e.emoji.length); maxName = Math.max(maxName, name.length); maxVersion = Math.max(maxVersion, e.version ?? 0)
}
const total = groups.reduce((n, g) => n + g.length, 0)

const out = `/**
 * data/OmniEmojiData.js — the full Unicode emoji set for the emoji picker and the "All emojis" demo store (V181)
 *
 * GENERATED by tools/build-emoji-data.mjs from emojibase-data ${pkg.version} (Unicode Emoji ${maxVersion}.0, MIT). Do not edit by hand; regenerate.
 * ${total} fully-qualified emoji in ${GROUP_NAMES.length} Unicode groups, no skin-tone variants. Longest emoji: ${maxUnits} UTF-16 units. Longest name: ${maxName} characters.
 * Pure data + tiny helpers, no DOM, no network.
 *
 * Shape of an entry: { e: emoji string, n: name ("Grinning face"), g: group index 0..${GROUP_NAMES.length - 1} (into GROUP_NAMES), k: [keywords] }
 */

export const SOURCE = { name: 'emojibase-data', version: '${pkg.version}', unicode: '${maxVersion}.0', generated: '${new Date().toISOString().slice(0, 10)}' }
export const GROUP_NAMES = ${JSON.stringify(GROUP_NAMES)}
export const GROUP_ICONS = ['😀', '👋', '🐻', '🍔', '✈️', '⚽', '💡', '🔣', '🏁']   // the picker's tab icons (one emoji per group)
export const EMOJI_COUNT = ${total}
export const EMOJI_MAX_UNITS = ${maxUnits}   // longest emoji string, in JS string length

// one string per group; a line is  HEX[-HEX...] <TAB> Name <TAB> keyword,keyword
const PACKED = [
${groups.map(g => '  ' + JSON.stringify(g.join('\n'))).join(',\n')},
]

let cache = null
const decode = (hex) => String.fromCodePoint(...hex.split('-').map(h => parseInt(h, 16)))

/** All entries, in Unicode order (group, then the standard order inside the group). Decoded once and cached; callers must not mutate. */
export function getEmojis () {
  if (cache) return cache
  const list = []
  PACKED.forEach((block, g) => {
    for (const line of block.split('\\n')) {
      const [hex, n, k] = line.split('\\t')
      list.push({ e: decode(hex), n, g, k: k ? k.split(',') : [] })
    }
  })
  cache = list
  return cache
}

/** Entries of one group (index 0..8). */
export const emojisOfGroup = (g) => getEmojis().filter(x => x.g === g)

/**
 * Search by name or keyword (case-insensitive, every word of the query must match somewhere: start of a word in the name / a keyword
 * scores best). Optional { group } limits to one group; { limit } caps the result (default 400). An empty query returns the group (or all).
 */
export function searchEmojis (query, { group = null, limit = 400 } = {}) {
  const all = getEmojis()
  const pool = group === null || group === undefined ? all : all.filter(x => x.g === group)
  const words = String(query ?? '').toLowerCase().split(/[\\s,]+/).filter(Boolean)
  if (!words.length) return pool.slice(0, limit)
  const scored = []
  for (const x of pool) {
    const name = x.n.toLowerCase()
    let score = 0
    for (const w of words) {
      let s = 0
      if (name === w) s = 100
      else if (name.startsWith(w)) s = 60
      else if (name.includes(' ' + w)) s = 40
      else if (x.k.some(t => t.toLowerCase() === w)) s = 30
      else if (name.includes(w)) s = 20
      else if (x.k.some(t => t.toLowerCase().includes(w))) s = 10
      else if (x.e === w) s = 100
      if (!s) { score = 0; break }
      score += s
    }
    if (score) scored.push([score, x])
  }
  scored.sort((a, b) => b[0] - a[0])   // stable: ties keep Unicode order
  return scored.slice(0, limit).map(p => p[1])
}

/** True when \`s\` is exactly one emoji of the set (as written, or with the text-style variation selector stripped / added). */
export function isKnownEmoji (s) {
  if (typeof s !== 'string' || !s) return false
  if (!knownSet) knownSet = new Set(getEmojis().map(x => x.e.replace(/\\uFE0F/g, '')))
  return knownSet.has(s.replace(/\\uFE0F/g, ''))
}
let knownSet = null

/** Look an emoji up (exact, ignoring FE0F). */
export function findEmoji (s) {
  const t = String(s ?? '').replace(/\\uFE0F/g, '')
  return getEmojis().find(x => x.e.replace(/\\uFE0F/g, '') === t) ?? null
}
`
fs.writeFileSync(outFile, out)
console.log(`wrote ${outFile}: ${total} emoji, ${out.length} bytes; groups ${groups.map(g => g.length).join('/')}; max units ${maxUnits}; max name ${maxName}`)
