#!/usr/bin/env node
/**
 * tools/build-docs-data.mjs — generates data/OmniDocsData.js (V190) from docs/user-guide/*.md. DEV TOOL, run when a guide page changes.
 *
 *   node tools/build-docs-data.mjs [--src docs/user-guide] [--out data/OmniDocsData.js] [--check]
 *
 * The in-app Docs panel (ui/OmniDocsPanel.js) and OmniStarLight read the bundled module, so the guide works with NO server and no
 * fetch. Pages: README.md first (id "index", title "Guide index"), then 01_..11_ in file order. 00_How_To_Maintain_This_Guide.md is
 * for developers and is excluded. Each page is { id, file, title, text, headings:[{level,text,id}] }; text is the raw markdown.
 * The output has no timestamp (same input -> same bytes) and carries a checksum; `--check` exits 1 when the file on disk is stale.
 * Run it from the project root after editing any user-guide page, and commit the regenerated data/OmniDocsData.js.
 */
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { docIdFromFile, extractHeadings, plainText } from '../utils/OmniDocsMarkdown.js'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const EXCLUDE = new Set(['00_How_To_Maintain_This_Guide.md'])

/** Pure: [{ file, text }] -> the page array (sorted: README first, then by file name). */
export function buildPages (files) {
  const list = files.filter(f => /\.md$/i.test(f.file) && !EXCLUDE.has(f.file))
  list.sort((a, b) => (/^readme/i.test(b.file) - /^readme/i.test(a.file)) || a.file.localeCompare(b.file))
  return list.map(({ file, text }) => {
    const id = docIdFromFile(file)
    const h1 = /^#\s+(.+?)\s*$/m.exec(text)
    let title = h1 ? plainText(h1[1]).replace(/^\d+\.\s*/, '') : id
    if (id === 'index') title = 'Guide index'
    return { id, file, title, text: text.replace(/\r\n/g, '\n'), headings: extractHeadings(text) }
  })
}

export function renderModule (pages) {
  const sum = crypto.createHash('sha256').update(JSON.stringify(pages)).digest('hex').slice(0, 16)
  const chars = pages.reduce((n, p) => n + p.text.length, 0)
  return `/**
 * data/OmniDocsData.js — the bundled user guide (V190). GENERATED by tools/build-docs-data.mjs from docs/user-guide/*.md.
 * DO NOT EDIT BY HAND: edit the markdown page, then run  node tools/build-docs-data.mjs  from the project root.
 * (00_How_To_Maintain_This_Guide.md is excluded: it is for developers.)  Read by ui/OmniDocsPanel.js and utils/OmniStarLightIndex.js.
 */

export const DOCS_META = ${JSON.stringify({ source: 'docs/user-guide', pages: pages.length, chars, checksum: sum })}

export const DOCS = ${JSON.stringify(pages, null, 1)}

export default DOCS
`
}

export function readFiles (dir) {
  return fs.readdirSync(dir).filter(f => /\.md$/i.test(f)).map(file => ({ file, text: fs.readFileSync(path.join(dir, file), 'utf8') }))
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d }
  const src = path.resolve(ROOT, arg('--src', 'docs/user-guide'))
  const out = path.resolve(ROOT, arg('--out', 'data/OmniDocsData.js'))
  const pages = buildPages(readFiles(src))
  const code = renderModule(pages)
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
    if (cur !== code) { console.error(`STALE: ${path.relative(ROOT, out)} does not match ${path.relative(ROOT, src)}. Run: node tools/build-docs-data.mjs`); process.exit(1) }
    console.log(`ok: ${path.relative(ROOT, out)} is up to date (${pages.length} pages)`); process.exit(0)
  }
  fs.writeFileSync(out, code)
  console.log(`wrote ${path.relative(ROOT, out)}: ${pages.length} pages, ${pages.reduce((n, p) => n + p.text.length, 0)} chars, ${pages.reduce((n, p) => n + p.headings.length, 0)} headings`)
  for (const p of pages) console.log(`  ${p.id.padEnd(34)} ${String(p.text.length).padStart(6)}  ${p.title}`)
}
